/**
 * Arabic. The layout already mirrors from `dirOf`, so what this file has to get right is the
 * language rather than the direction.
 *
 * Two things the shared templates could not have done. The definite article attaches to the
 * word — "صورة جواز السفر", not "صورة جواز سفر" — so the document names below carry it. And
 * "لـ" attaches to the country with no space, which is why the page title is built here and
 * not by concatenation somewhere else.
 */

/**
 * The preposition "ل" merges with a following definite article: لـ + الهند is للهند, not
 * لـالهند. Countries whose ICU name carries the article are the majority here — الهند,
 * الصين, المملكة المتحدة — so a plain concatenation is wrong more often than it is right.
 */
function forCountry(country: string): string {
  return country.startsWith("ال") ? `لل${country.slice(2)}` : `ل${country}`;
}

